class Q42Error(Rel42Error):
    pass


# A vector: basis value -> amplitude.  Absent keys are zero.
Vec = Dict[Value, complex]

TOL = 1e-12

ZERO: Value = Inl(UNIT)  # |0>
ONE: Value = Inr(UNIT)  # |1>
BIT = [ZERO, ONE]


def normalise(v: Vec) -> Vec:
    """Drop amplitudes that are zero to within tolerance."""
    return {k: z for k, z in v.items() if abs(z) > TOL}


# ---------------------------------------------------------------------------
# Primitives.  Each is a pair (forward, backward) from a basis value to a
# *column*.  The backward leg is the adjoint, where 42's was the converse --
# that substitution is the whole of the semiring change at this level.
# ---------------------------------------------------------------------------

PRIMS: Dict[str, Tuple[Callable[[Value], Vec], Callable[[Value], Vec]]] = {}


def _prim(name: str, fwd, bwd) -> None:
    PRIMS[name] = (fwd, bwd)


def _one(v: Value) -> Vec:
    return {v: 1 + 0j}


_prim("id", _one, _one)


# additive structure --------------------------------------------------------
def _swapsum(v: Value) -> Vec:
    match v:
        case Inl(x):
            return {Inr(x): 1 + 0j}
        case Inr(x):
            return {Inl(x): 1 + 0j}
    return {}


_prim("swapsum", _swapsum, _swapsum)  # self-inverse; this is Pauli X


def _assocsum(v: Value) -> Vec:  # a + (b + c)  ->  (a + b) + c
    match v:
        case Inl(x):
            return {Inl(Inl(x)): 1 + 0j}
        case Inr(Inl(x)):
            return {Inl(Inr(x)): 1 + 0j}
        case Inr(Inr(x)):
            return {Inr(x): 1 + 0j}
    return {}


def _assocsum_b(v: Value) -> Vec:
    match v:
        case Inl(Inl(x)):
            return {Inl(x): 1 + 0j}
        case Inl(Inr(x)):
            return {Inr(Inl(x)): 1 + 0j}
        case Inr(x):
            return {Inr(Inr(x)): 1 + 0j}
    return {}


_prim("assocsum", _assocsum, _assocsum_b)

_prim(
    "unitsum",  # 0 + a  <->  a;  the 0 side is uninhabited
    lambda v: {v.v: 1 + 0j} if isinstance(v, Inr) else {},
    lambda v: {Inr(v): 1 + 0j},
)


# multiplicative structure --------------------------------------------------
def _swapprod(v: Value) -> Vec:
    return {Pair(v.b, v.a): 1 + 0j} if isinstance(v, Pair) else {}


_prim("swapprod", _swapprod, _swapprod)  # self-inverse; this is SWAP


def _assocprod(v: Value) -> Vec:  # (a, (b, c))  ->  ((a, b), c)
    match v:
        case Pair(a, Pair(b, c)):
            return {Pair(Pair(a, b), c): 1 + 0j}
    return {}


def _assocprod_b(v: Value) -> Vec:
    match v:
        case Pair(Pair(a, b), c):
            return {Pair(a, Pair(b, c)): 1 + 0j}
    return {}


_prim("assocprod", _assocprod, _assocprod_b)

_prim(
    "unitprod",  # 1 x a  <->  a
    lambda v: {v.b: 1 + 0j} if isinstance(v, Pair) and v.a == UNIT else {},
    lambda v: {Pair(UNIT, v): 1 + 0j},
)


# distributivity -- and, via `mat` in gates.42, every controlled gate ---------
def _dist(v: Value) -> Vec:  # (a + b) x c  ->  (a x c) + (b x c)
    match v:
        case Pair(Inl(a), c):
            return {Inl(Pair(a, c)): 1 + 0j}
        case Pair(Inr(b), c):
            return {Inr(Pair(b, c)): 1 + 0j}
    return {}


def _dist_b(v: Value) -> Vec:
    match v:
        case Inl(Pair(a, c)):
            return {Pair(Inl(a), c): 1 + 0j}
        case Inr(Pair(b, c)):
            return {Pair(Inr(b), c): 1 + 0j}
    return {}


_prim("dist", _dist, _dist_b)


# ---------------------------------------------------------------------------
# The two generators.  Everything above is a permutation matrix and would mean
# the same thing over any semiring; these two are what C buys.
#
#   (E1)  omega^8 = id
#   (E2)  v ; v = swapsum
#   (E3)  v ; S ; v = omega^2 . (S ; v ; S)      where  S = id + omega^2
#
# (E1) and (E2) only assert that the square roots exist.  (E3) is the one that
# does work: without it `omega = id` is consistent and the model is not
# universal.  It says the pi/2 rotations decompose alike along ZXZ and XZX,
# which is the Euler decomposition of the Hadamard gate.
# ---------------------------------------------------------------------------

OMEGA = cmath.exp(1j * cmath.pi / 4)  # a primitive 8th root of unity

_prim(
    "omega",
    lambda v: {UNIT: OMEGA} if isinstance(v, Unit) else {},
    lambda v: {UNIT: OMEGA.conjugate()} if isinstance(v, Unit) else {},
)

# V = H . diag(-1, i) . H, in the basis |0> = Inl (), |1> = Inr ().  Any square
# root of X satisfies (E2); this is the one that also satisfies (E3).
V_MATRIX = [
    [(-1 + 1j) / 2, (-1 - 1j) / 2],
    [(-1 - 1j) / 2, (-1 + 1j) / 2],
]


def _from_matrix(m, basis, adjoint: bool = False):
    def go(v: Value) -> Vec:
        if v not in basis:
            return {}
        j = basis.index(v)
        if adjoint:  # column j of M-dagger is the conjugate of row j of M
            return {basis[i]: m[j][i].conjugate() for i in range(len(basis))}
        return {basis[i]: m[i][j] for i in range(len(basis))}

    return go


_prim("v", _from_matrix(V_MATRIX, BIT), _from_matrix(V_MATRIX, BIT, adjoint=True))


