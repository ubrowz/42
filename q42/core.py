"""Q42 -- 42 over C.  Values, unitary primitives, and the evaluator.

42 is interpreted in Rel: matrices over the Boolean semiring.  Q42 is
interpreted in Unitary: finite-dimensional Hilbert spaces and unitary maps,
matrices over C.  See Q42.md for the design and its provenance; the short
version is that 42's primitive set is a presentation of a *rig groupoid*, and
Carette, Heunen, Kaarsgaard & Sabry (POPL 2024) showed that a rig groupoid plus
two maps and three equations is computationally universal for quantum computing.
Those two maps are `omega` and `v` below.

What is reused from rel42, unchanged:

    core.Value      the universe generated by 0, 1, +, x
    core.Term       the abstract syntax
    core.dagger     inversion -- the *same function*, not a reimplementation
    syntax          the lexer and parser, given Q42's primitive names
    types           unification and inference, given Q42's primitive schemes

What is new here: the primitive table (adjoints rather than converses) and an
evaluator whose columns are amplitudes rather than sets.

Two constructors of the shared term language are rejected rather than
interpreted.  `Union` (`|`) and `Star` (`^`) are exactly the two whose meaning
depends on addition in the semiring being *idempotent* -- `f | f` would denote
`2f`, and `Star`'s saturation is a least fixed point needing `1 + 1 = 1`.  C's
addition is not idempotent, so neither survives, and no design judgement is
involved.  Note that dropping `|` costs nothing in expressiveness: superposition
comes from applying `v` to a basis state, not from a choice construct.
"""

