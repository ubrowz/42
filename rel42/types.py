def references(t: Term) -> Set[str]:
    """Every definition named anywhere in a term."""
    out: Set[str] = set()
    stack: List[Term] = [t]
    while stack:
        u = stack.pop()
        match u:
            case Ref(name, _):
                out.add(name)
            case Seq(s, v) | Union(s, v) | Sum(s, v) | Prod(s, v) | App(s, v):
                stack += [s, v]
            case Star(s) | Fun(_, s):
                stack.append(s)
    return out


def _arity(t: Term) -> int:
    """How many parameters a definition takes."""
    return 1 + _arity(t.body) if isinstance(t, Fun) else 0


def groups(defs: Dict[str, Term]) -> List[List[str]]:
    """Mutually recursive groups, dependencies first (Tarjan).

    A group of one that does not name itself is an ordinary definition.
    Anything else is recursive and must be solved as a unit.
    """
    deps = {n: references(b) & defs.keys() for n, b in defs.items()}
    index: Dict[str, int] = {}
    low: Dict[str, int] = {}
    onstack: Dict[str, bool] = {}
    stack: List[str] = []
    out: List[List[str]] = []
    counter = 0

    def strong(v: str) -> None:
        nonlocal counter
        index[v] = low[v] = counter
        counter += 1
        stack.append(v)
        onstack[v] = True
        for w in sorted(deps[v]):
            if w not in index:
                strong(w)
                low[v] = min(low[v], low[w])
            elif onstack.get(w):
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp: List[str] = []
            while True:
                w = stack.pop()
                onstack[w] = False
                comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp))

    for n in defs:
        if n not in index:
            strong(n)
    return out


def infer_program(
    defs: Dict[str, Term], prims: Dict[str, Scheme] | None = None
) -> Tuple[Dict[str, Scheme], Dict[str, Exception]]:
    """Type every definition it can, and report why the rest failed.

    Deliberately does not stop at the first error: on a file of twenty
    definitions the useful output is which nineteen were fine.
    """
    schemes: Dict[str, Scheme] = {}
    errors: Dict[str, Exception] = {}

    for comp in groups(defs):
        blocked = sorted(
            {
                m
                for n in comp
                for m in (references(defs[n]) & defs.keys())
                if m not in comp and m not in schemes
            }
        )
        if blocked:
            for n in comp:
                errors[n] = IllTyped(
                    f"depends on {', '.join(blocked)}, which did not typecheck"
                )
            continue

        inf = Inference(prims)
        recursive = len(comp) > 1 or comp[0] in references(defs[comp[0]])
        try:
            if not recursive:
                name = comp[0]
                schemes[name] = inf.generalise(inf.infer(defs[name], schemes))
            else:
                # Monomorphic assumptions for the whole group, then solve the
                # bodies against them.  Generalise only once all are consistent.
                assume = {
                    n: Scheme(
                        inf.fresh(),
                        inf.fresh(),
                        mono=True,
                        params=tuple(
                            (inf.fresh(), inf.fresh()) for _ in range(_arity(defs[n]))
                        ),
                    )
                    for n in comp
                }
                env = {**schemes, **assume}
                for n in comp:
                    got = inf.infer(defs[n], env)
                    why = f"in the recursive definition of `{n}`"
                    inf.unify_scheme(got, assume[n], why)
                for n in comp:
                    schemes[n] = inf.generalise(assume[n])
        except Rel42Error as e:
            for n in comp:
                errors.setdefault(n, e)
    return schemes, errors


def infer_term(
    t: Term, env: Dict[str, Scheme], prims: Dict[str, Scheme] | None = None
) -> Scheme:
    """The type of a single term against already-typed definitions."""
    inf = Inference(prims)
    return inf.generalise(inf.infer(t, env))


# ---------------------------------------------------------------------------
# Do values fit types?
# ---------------------------------------------------------------------------


def conform(
    v: Value, t: Type, seen: FrozenSet[Tuple[int, Type]] = frozenset()
) -> Tuple[Value, Type] | None:
    """`None` if `v` inhabits `t`; otherwise the innermost pair that clashed.

    A free variable accepts anything.  It is universally quantified, so the
    caller chooses what it stands for, and a value is evidence of that choice
    rather than a violation of it -- `succ : a <-> b + a` really does accept any
    value at all on the left.

    A `mu` is checked by unfolding, which terminates because every recursive
    type that survived `Inference._bind` is guarded: one unfolding exposes a
    constructor, which consumes a layer of the (finite) value.  `seen` guards
    the pathological case anyway rather than trusting that argument.
    """
    match t:
        case TVar(_):
            return None
        case TOne():
            return None if isinstance(v, Unit) else (v, t)
        case TZero():
            return v, t  # nothing inhabits 0
        case TSum(a, b):
            if isinstance(v, Inl):
                return conform(v.v, a, seen)
            if isinstance(v, Inr):
                return conform(v.v, b, seen)
            return v, t
        case TProd(a, b):
            if not isinstance(v, Pair):
                return v, t
            return conform(v.a, a, seen) or conform(v.b, b, seen)
        case TMu(_, _):
            key = (id(v), t)
            if key in seen:
                return v, t
            return conform(v, unfold(t), seen | {key})
    return v, t


def names_for(*ts: Type) -> Dict[int, str]:
    """Canonical variable names, shared across several types so they line up."""
    return _label(*ts)


# ---------------------------------------------------------------------------
# Abbreviations.
#
# Inferred types are correct and nearly unreadable:
#
#     divmod : (mu X. a + X) x (b + (mu Y. 1 + Y)) <-> ...
#
# Declaring `type nat = mu X. 1 + X` lets the printer say `nat` instead.  This is
# a *display* layer and nothing more: no new primitives, no new semantics, and
# the checker behaves identically whether or not any abbreviation is declared.
#
# Matching has to be up to equirecursive equality, because the same infinite tree
# has many presentations -- `nat`, `1 + nat`, and the shifted forms `refold`
# cannot collapse.  Unification already decides that question, so `match_type`
# is unification's one-way sibling: pattern variables listed in `params` may
# bind, everything else must agree on the nose.
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Abbrev:
    """`type name p1 p2 = body`."""

    name: str
    params: Tuple[int, ...]
    body: Type


def match_type(
    pattern: Type,
    subject: Type,
    params: FrozenSet[int],
    subst: Dict[int, Type] | None = None,
    seen: FrozenSet[Tuple[Type, Type]] = frozenset(),
) -> Dict[int, Type] | None:
    """One-way match, up to unfolding.  `None` if the shapes differ.

    Unlike `unify` this never binds a variable of the *subject*: an abbreviation
    must describe the type it is offered, not constrain it.  Without that,
    `type nat = mu X. 1 + X` would match every type variable and every inferred
    type would print as `nat`.
    """
    subst = {} if subst is None else subst
    if (pattern, subject) in seen:
        return subst
    seen = seen | {(pattern, subject)}

    if isinstance(pattern, TVar) and pattern.id in params:
        bound = subst.get(pattern.id)
        if bound is None:
            subst[pattern.id] = subject
            return subst
        return subst if match_type(bound, subject, frozenset(), {}, seen) else None

    if isinstance(pattern, TMu):
        return match_type(unfold(pattern), subject, params, subst, seen)
    if isinstance(subject, TMu):
        return match_type(pattern, unfold(subject), params, subst, seen)

    match (pattern, subject):
        case (TZero(), TZero()) | (TOne(), TOne()):
            return subst
        case (TVar(i), TVar(j)):
            return subst if i == j else None
        case (TSum(a, b), TSum(c, d)) | (TProd(a, b), TProd(c, d)):
            if match_type(a, c, params, subst, seen) is None:
                return None
            return match_type(b, d, params, subst, seen)
    return None


# ---------------------------------------------------------------------------
# Printing.  `+` binds looser than `x`, matching the term grammar, so a sum
# inside a product needs brackets and nothing else does.  `mu` is looser still.
# ---------------------------------------------------------------------------

# `x` is the product operator in type syntax, so it is not available as a
# variable name -- `(x + x) x (a + b)` would be unreadable and unparseable.
_LETTERS = "abcdefghijklmnopqrstuvwyz"
_BOUND = "XYZWVU"


def _label(*ts: Type, pin: int | None = None) -> Dict[int, str]:
    """Names for the variables in `ts`.

    Recursive binders get `X`, `Y`, ... and free variables `a`, `b`, ..., so
    that reading a printed type tells you which is which.  `pin` names one
    variable `X` up front, for messages about a cycle not yet turned into a
    `TMu`.
    """
    free: List[int] = []
    bound: List[int] = []

    def walk(t: Type) -> None:
        match t:
            case TVar(i):
                free.append(i)
            case TSum(a, b) | TProd(a, b):
                walk(a)
                walk(b)
            case TMu(v, body):
                bound.append(v)
                walk(body)

    for t in ts:
        walk(t)

    out: Dict[int, str] = {}
    n = 0
    if pin is not None:
        out[pin] = _BOUND[0]
        n = 1
    for i in bound:
        if i not in out:
            out[i] = _BOUND[n] if n < len(_BOUND) else f"X{n}"
            n += 1
    m = 0
    for i in free:
        if i not in out:
            out[i] = _LETTERS[m] if m < len(_LETTERS) else f"t{m}"
            m += 1
    return out


def _names(s: Scheme) -> Dict[int, str]:
    return _label(*[x for pair in s.params for x in pair], s.dom, s.cod)


def show_type(
    t: Type,
    names: Dict[int, str] | None = None,
    ctx: int = 0,
    abbrevs: Sequence["Abbrev"] = (),
    depth: int = 12,
) -> str:
    """Render a type.

    `abbrevs` are tried at every node, in declaration order, first match winning
    -- so declare the more specific ones first.

    Neither `+` nor `x` is associative here -- `(a x b) x c` and `a x (b x c)`
    are different shapes, and `assocprod` is the term that converts between
    them -- so the printer must not silently flatten either one.  Both are shown
    left-associatively, matching the term grammar, and a right-nested operand is
    bracketed.

    `ctx` is the tightest level that still prints bare: 0 sums and `mu`,
    1 products, 2 atoms only.
    """
    if depth > 0:
        for ab in abbrevs:
            found = match_type(ab.body, t, frozenset(ab.params))
            if found is None:
                continue
            if not ab.params:
                return ab.name
            args = " ".join(
                show_type(found.get(p, TVar(p)), names, 2, abbrevs, depth - 1)
                for p in ab.params
            )
            return f"({ab.name} {args})" if ctx > 1 else f"{ab.name} {args}"

    def go(u: Type, c: int) -> str:
        return show_type(u, names, c, abbrevs, depth - 1)

    match t:
        case TVar(i):
            return names[i] if names and i in names else f"?{i}"
        case TZero():
            return "0"
        case TOne():
            return "1"
        case TMu(v, body):
            name = names[v] if names and v in names else f"?{v}"
            s = f"mu {name}. {go(body, 0)}"
            return f"({s})" if ctx > 0 else s
        case TSum(a, b):
            s = f"{go(a, 0)} + {go(b, 1)}"
            return f"({s})" if ctx > 0 else s
        case TProd(a, b):
            s = f"{go(a, 1)} x {go(b, 2)}"
            return f"({s})" if ctx > 1 else s
    raise Rel42Error(f"not a type: {t!r}")


def show_scheme(s: Scheme, abbrevs: Sequence["Abbrev"] = ()) -> str:
    names = _label(*[x for pair in s.params for x in pair], s.dom, s.cod)

    def one(t: Type) -> str:
        return show_type(t, names, 0, abbrevs)

    body = f"{one(s.dom)} <-> {one(s.cod)}"
    if not s.params:
        return body
    args = " -> ".join(f"({one(a)} <-> {one(b)})" for a, b in s.params)
    return f"{args} -> ({body})"
