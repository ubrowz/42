"""Types for 42 -- shapes for the relations that terms denote.

A term denotes a relation, so its type has two sides:

    t : A <-> B      means    [[t]]  is a subset of  A x B

Types are the trees generated by the same four things the values are:

    0            uninhabited
    1            one inhabitant
    A + B        labelled
    A x B        paired

plus variables, because the plumbing is polymorphic (`swapprod` rearranges any
pair, so its type is `a x b <-> b x a`), plus `mu X. F(X)` for the recursive
ones, because `nat` and `list` are not finite trees.

Recursion is **equirecursive**: `mu X. F(X)` and `F(mu X. F(X))` are the same
type, silently, with no `fold`/`unfold` in the language and no change to any
program that was already written.  A `mu` is not a construct the programmer
reaches for -- it is what the checker *infers* when unification closes a loop.
`nat` is not declared anywhere; it appears because `succ = inr` composed with
itself demands it.

Four things are worth stating up front, because each is forced by the setting
rather than chosen, and each is checked in tests/test_types.py.

**Inversion swaps the two sides.**  If `t : A <-> B` then `t! : B <-> A`, and
nothing else about the type changes.  This is the type-level shadow of the
defining law: `dagger` is contravariant on composition and identity-on-objects,
so at the level of shapes it can only exchange domain and codomain.  Inference
implements `inv` by literally swapping a scheme, so the property holds by
construction.

**Generalisation is nearly trivial, because 42 has almost no binders.**  Every
definition is a closed term -- no lambda, no local name -- so a non-recursive
definition generalises over all its free variables and none of the usual
machinery (levels, ranks, the value restriction) is needed.  The one exception is
a group of mutually recursive definitions, which are typed together against
*monomorphic* assumptions and generalised only once the group is done.  That is
Milner-style recursion: polymorphic recursion is undecidable in general, and
nothing in the libraries wants it.

**A cycle in unification is the recursive type, not a failure.**  Where a
finite-tree checker runs an occurs check and gives up, this one binds the
variable to a term containing itself and carries on; the cycle *is* `mu`.  So
`downfrom = pred^` demands `b = a + b` and gets `mu X. a + X`.  Unification then
has to work up to unfolding, which it does coinductively: assume the two sides
equal, and check that the assumption survives one layer.  The set of assumptions
is what makes it terminate.

**But a cycle still has to be read before it is trusted.**  Not every recursive
equation describes a type with values in it:

    b = a + b     is  mu X. a + X   -- a list.  Has finite values.
    a = a x a     is  mu X. X x X   -- infinite trees only.  Has none.

The first is a good type; the second is a fault in the program that no amount of
recursion will rescue, and `copy^` is how you write it.  They are told apart by
one unfolding with the recursive variable taken to be empty: `mu X. F(X)` has a
finite value exactly when `F(0)` does.  If `F(0)` is empty then so is `F(F(0))`,
so one step settles it.

Internally a recursive type is a *cycle in the substitution* rather than a `TMu`
node -- that is what makes unification fall out of ordinary variable binding.
`TMu` appears only in the canonical form, produced by `Inference.apply` when a
type is read out of the solver for storing or printing.
"""

