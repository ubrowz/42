# ---------------------------------------------------------------------------
# Types.
# ---------------------------------------------------------------------------


class Type:
    __slots__ = ()


@dataclass(frozen=True)
class TVar(Type):
    """A variable.  Free ones are generalised; `TMu` binds one."""

    id: int


@dataclass(frozen=True)
class TZero(Type):
    """The empty type.  No values inhabit it."""


@dataclass(frozen=True)
class TOne(Type):
    """The unit type.  `()` is its only value."""


@dataclass(frozen=True)
class TSum(Type):
    a: Type
    b: Type


@dataclass(frozen=True)
class TProd(Type):
    a: Type
    b: Type


@dataclass(frozen=True)
class TMu(Type):
    """`mu var. body` -- equal to its own unfolding, and never written by hand."""

    var: int
    body: Type


@dataclass(frozen=True)
class Scheme:
    """A type for a term.

    A relation has `params = ()` and reads `dom <-> cod`.  A combinator carries
    one `(dom, cod)` pair per parameter, outermost first, and reads

        (a <-> b) -> (c <-> d)

    No general arrow type is needed, and that falls out of the second-order
    restriction in `core`: a parameter always denotes a relation, never another
    combinator, so a combinator's type is fully described by a list of parameter
    relation-types plus the relation it finally denotes.

    Generalised over every free variable, except while a recursive group is
    being solved: `mono` marks an assumption that must be used as-is rather
    than freshened at each occurrence.
    """

    dom: Type
    cod: Type
    mono: bool = False
    params: Tuple[Tuple[Type, Type], ...] = ()

    @property
    def is_combinator(self) -> bool:
        return bool(self.params)

    def swap(self) -> "Scheme":
        """The type of the dagger.

        The parameters are *not* swapped, only the result.  That is forced by
        `core.dagger`'s convention: inversion pushes onto the variable's flag and
        substitution discharges it, so `dagger(ctrl)` still accepts an argument of
        the same type and returns the adjoint of what `ctrl` returned.
        """
        return Scheme(self.cod, self.dom, self.mono, self.params)


