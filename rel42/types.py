class IllTyped(Rel42Error):
    """Two shapes clash, or a recursive type would have no values.

    Either way the program is wrong.  At runtime it would denote the empty
    relation, which is a legitimate morphism of Rel, so the interpreter cannot
    report it; that silence is exactly what a type system is for.
    """


# ---------------------------------------------------------------------------
# Primitive schemes.  These *are* the isomorphisms witnessing the commutative
# semiring structure of (0, 1, +, x), which is why the table reads like the
# semiring axioms: that is what the primitives were chosen to be.
# ---------------------------------------------------------------------------

_a, _b, _c = TVar(0), TVar(1), TVar(2)

PRIM_SCHEMES: Dict[str, Scheme] = {
    # identity, and the empty relation between any two shapes at all
    "id": Scheme(_a, _a),
    "zero": Scheme(_a, _b),
    # additive structure
    "swapsum": Scheme(TSum(_a, _b), TSum(_b, _a)),
    "assocsum": Scheme(TSum(_a, TSum(_b, _c)), TSum(TSum(_a, _b), _c)),
    "unitsum": Scheme(TSum(TZero(), _a), _a),
    # multiplicative structure
    "swapprod": Scheme(TProd(_a, _b), TProd(_b, _a)),
    "assocprod": Scheme(TProd(_a, TProd(_b, _c)), TProd(TProd(_a, _b), _c)),
    "unitprod": Scheme(TProd(TOne(), _a), _a),
    # distributivity
    "dist": Scheme(
        TProd(TSum(_a, _b), _c), TSum(TProd(_a, _c), TProd(_b, _c))
    ),
    # injections: partial injections, so the other summand is unconstrained
    "inl": Scheme(_a, TSum(_a, _b)),
    "inr": Scheme(_b, TSum(_a, _b)),
    # the two that make this Rel rather than a groupoid
    "copy": Scheme(_a, TProd(_a, _a)),
    "join": Scheme(TSum(_a, _a), _a),
}


# ---------------------------------------------------------------------------
# Operations on canonical (TMu-carrying) types.
# ---------------------------------------------------------------------------


def unfold(t: TMu) -> Type:
    """One layer off a `mu`.  Equirecursively this changes nothing."""
    return replace_var(t.body, t.var, t)


def replace_var(t: Type, i: int, repl: Type) -> Type:
    """Substitute for a free occurrence of variable `i`, respecting binders."""
    match t:
        case TVar(j):
            return repl if i == j else t
        case TSum(a, b):
            return TSum(replace_var(a, i, repl), replace_var(b, i, repl))
        case TProd(a, b):
            return TProd(replace_var(a, i, repl), replace_var(b, i, repl))
        case TMu(v, body):
            return t if v == i else TMu(v, replace_var(body, i, repl))
    return t


def _mus_in(t: Type) -> Iterator[TMu]:
    """Every `mu` node anywhere in `t`.

    Not just the immediate children: the list case hides its recursion one level
    down, in `1 + a x (mu X. 1 + a x X)`, where the `mu` sits inside the product.
    """
    if isinstance(t, TMu):
        yield t
    match t:
        case TSum(a, b) | TProd(a, b):
            yield from _mus_in(a)
            yield from _mus_in(b)
        case TMu(_, body):
            yield from _mus_in(body)


def refold(t: Type) -> Type:
    """Collapse `F(mu X. F(X))` back to `mu X. F(X)`.

    Equirecursive types have no unique syntactic form, and canonicalising one
    properly means minimising a regular tree.  This is the cheap half: it
    recognises a type that is literally one unfolding of a `mu` occurring inside
    it, which is the shape unification leaves behind whenever it closes a loop
    below the root -- `pred^` produces `a + (mu X. a + X)` and means
    `mu X. a + X`.

    Deeper coincidences are left alone.  `mu X. b + (a + X)` and
    `mu Y. a + (b + Y)` denote the same infinite tree but no single unfolding
    relates them, so both may appear in one file.  That is wordier than
    necessary, never wrong.
    """
    match t:
        case TSum(a, b):
            folded: Type = TSum(refold(a), refold(b))
        case TProd(a, b):
            folded = TProd(refold(a), refold(b))
        case TMu(v, body):
            folded = TMu(v, refold(body))
        case _:
            return t
    for m in _mus_in(folded):
        if unfold(m) == folded:
            return m
    return folded


def inhabited(t: Type, empty: FrozenSet[int] = frozenset()) -> bool:
    """Does this type have any finite value?

    `empty` holds recursive variables taken to be uninhabited, which is what
    makes `mu X. X x X` come out false and `mu X. 1 + X` come out true.  A free
    variable counts as inhabited: it is universally quantified, so it stands for
    whatever the caller supplies, and nothing here should decide otherwise.
    """
    match t:
        case TZero():
            return False
        case TOne():
            return True
        case TVar(i):
            return i not in empty
        case TSum(a, b):
            return inhabited(a, empty) or inhabited(b, empty)
        case TProd(a, b):
            return inhabited(a, empty) and inhabited(b, empty)
        case TMu(v, body):
            return inhabited(body, empty | {v})
    return True


