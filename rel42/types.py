class Inference:
    """Unification state for one run of the checker.

    Kept as an object rather than threaded through as arguments because the
    substitution and the fresh-variable counter are both single-writer and
    every rule touches them.  The substitution may be *cyclic*: that is how a
    recursive type is represented while being solved.
    """

    def __init__(self, prims: Dict[str, Scheme] | None = None) -> None:
        self.subst: Dict[int, Type] = {}
        self._next = 1000  # above the small ids used in PRIM_SCHEMES
        # The primitive signatures.  Injected so that a sibling language over the
        # same term grammar -- q42, whose primitives are unitaries rather than
        # relations -- reuses this engine whole rather than forking it.
        self.prims = PRIM_SCHEMES if prims is None else prims

    # -- variables ---------------------------------------------------------

    def fresh(self) -> TVar:
        self._next += 1
        return TVar(self._next)

    def resolve(self, t: Type) -> Type:
        """Follow variable bindings at the root only.

        Terminates even with a cyclic substitution: a variable is only ever
        bound while unbound, so a chain of pure variable indirections cannot
        close into a loop, and any cycle passes through a constructor.
        """
        while isinstance(t, TVar) and t.id in self.subst:
            t = self.subst[t.id]
        return t

    def apply(self, t: Type) -> Type:
        """Read a type out of the solver, in canonical form.

        Any cycle reached on the way becomes an explicit `mu`.  This is the only
        place `TMu` is built.
        """
        return refold(self._canon(t, ())[0])

    def _canon(self, t: Type, path: Tuple[int, ...]) -> Tuple[Type, Set[int]]:
        """Expand `t`, returning it and the path variables it loops back to."""
        if isinstance(t, TVar):
            if t.id in path:
                return t, {t.id}  # a back-edge: some binder above owns this
            if t.id in self.subst:
                body, used = self._canon(self.subst[t.id], path + (t.id,))
                if t.id in used:
                    return TMu(t.id, body), used - {t.id}
                return body, used
            return t, set()
        match t:
            case TSum(a, b):
                ca, ua = self._canon(a, path)
                cb, ub = self._canon(b, path)
                return TSum(ca, cb), ua | ub
            case TProd(a, b):
                ca, ua = self._canon(a, path)
                cb, ub = self._canon(b, path)
                return TProd(ca, cb), ua | ub
            case TMu(v, body):
                cb, used = self._canon(body, path)
                return TMu(v, cb), used - {v}
        return t, set()

    def instantiate(self, s: Scheme) -> Scheme:
        """Freshen every variable.  Both sides share one renaming.

        A monomorphic assumption -- a member of the recursive group currently
        being solved -- is returned untouched, which is what ties the recursive
        occurrences to the definition being checked.
        """
        if s.mono:
            return s
        mapping: Dict[int, TVar] = {}

        def go(t: Type) -> Type:
            match t:
                case TVar(i):
                    return mapping.setdefault(i, self.fresh())
                case TSum(a, b):
                    return TSum(go(a), go(b))
                case TProd(a, b):
                    return TProd(go(a), go(b))
                case TMu(v, body):
                    # The binder is renamed like anything else; consistently,
                    # so the body's back-references still point at it.
                    return TMu(mapping.setdefault(v, self.fresh()).id, go(body))
            return t

        return Scheme(
            go(s.dom),
            go(s.cod),
            params=tuple((go(a), go(b)) for a, b in s.params),
        )

    # -- unification -------------------------------------------------------

    def occurs(
        self, i: int, t: Type, seen: FrozenSet[Type] = frozenset()
    ) -> bool:
        """Does variable `i` appear in `t`?

        `seen` plays the role `assumed` plays in `unify`.  Substitutions here
        are deliberately cyclic -- that is what makes the types equirecursive --
        so a naive walk follows a cycle forever.  Cutting at an already-visited
        node is sound because this is a reachability question: arriving somewhere
        twice on one path cannot reveal an occurrence the first visit missed.
        """
        t = self.resolve(t)
        if t in seen:
            return False
        seen = seen | {t}
        match t:
            case TVar(j):
                return i == j
            case TSum(a, b) | TProd(a, b):
                return self.occurs(i, a, seen) or self.occurs(i, b, seen)
            case TMu(v, body):
                return i != v and self.occurs(i, body, seen)
        return False

    def unify(
        self,
        x: Type,
        y: Type,
        why: str,
        assumed: FrozenSet[Tuple[Type, Type]] = frozenset(),
    ) -> None:
        """Unify up to unfolding of `mu`.

        `assumed` carries the coinductive hypotheses: pairs already taken to be
        equal further up this derivation.  Without it, two recursive types would
        unfold against each other forever; with it, the recursion is bounded by
        the number of distinct resolved pairs, which is finite for the regular
        trees a cyclic substitution can describe.
        """
        x, y = self.resolve(x), self.resolve(y)
        if x == y or (x, y) in assumed:
            return
        assumed = assumed | {(x, y)}

        if isinstance(x, TVar):
            self._bind(x, y, why)
            return
        if isinstance(y, TVar):
            self._bind(y, x, why)
            return

        # A `mu` is equal to its unfolding, so peel and continue.  The
        # assumption added above is what stops this from being circular.
        if isinstance(x, TMu):
            return self.unify(unfold(x), y, why, assumed)
        if isinstance(y, TMu):
            return self.unify(x, unfold(y), why, assumed)

        match (x, y):
            case (TSum(a, b), TSum(c, d)) | (TProd(a, b), TProd(c, d)):
                self.unify(a, c, why, assumed)
                self.unify(b, d, why, assumed)
                return

        names = _label(x, y)
        raise IllTyped(
            f"{why}: cannot match {show_type(x, names)} "
            f"with {show_type(y, names)}"
        )

    def _bind(self, x: TVar, y: Type, why: str) -> None:
        """Bind a variable, allowing a cycle -- but only an inhabited one.

        Binding `X := F(X)` is how a recursive type is created, and it is
        usually right.  It is wrong exactly when `mu X. F(X)` has no finite
        values, because then the program has demanded something no value can
        satisfy.  See the module docstring.
        """
        if self.occurs(x.id, y):
            body = self.apply(y)
            if not inhabited(replace_var(body, x.id, TZero())):
                shown = show_type(body, _label(body, pin=x.id))
                raise IllTyped(
                    f"{why}: X would have to equal {shown}, and mu X. {shown} "
                    f"has no finite values -- no recursive type can rescue this"
                )
        self.subst[x.id] = y

    def generalise(self, s: Scheme) -> Scheme:
        """Read a whole type out of the solver, in canonical form."""
        return Scheme(
            self.apply(s.dom),
            self.apply(s.cod),
            params=tuple((self.apply(a), self.apply(b)) for a, b in s.params),
        )

    def relation(
        self, t: Term, env: Dict[str, Scheme], where: str
    ) -> Tuple[Type, Type]:
        """Infer `t` and insist it denotes a relation rather than a combinator.

        Every operator of the language composes relations, so an unapplied
        combinator in any of those positions is a missing argument.
        """
        s = self.infer(t, env)
        if s.params:
            raise IllTyped(
                f"{where} is a combinator awaiting {len(s.params)} more "
                f"argument(s), not a relation"
            )
        return s.dom, s.cod

    def unify_scheme(self, x: Scheme, y: Scheme, why: str) -> None:
        """Unify two whole types, parameters included."""
        if len(x.params) != len(y.params):
            raise IllTyped(
                f"{why}: one takes {len(x.params)} parameter(s) and the other "
                f"{len(y.params)}"
            )
        for (a, b), (c, d) in zip(x.params, y.params):
            self.unify(a, c, why)
            self.unify(b, d, why)
        self.unify(x.dom, y.dom, why)
        self.unify(x.cod, y.cod, why)

    # -- the rules ---------------------------------------------------------

    def infer(self, t: Term, env: Dict[str, Scheme]) -> Scheme:
        """The type of a term.

        One rule per constructor, and each is the obvious one -- `;` matches the
        middle, `|` matches both ends, `+` and `*` are functors, `^` forces the
        two ends together, and `!` swaps them.  Abstraction and application add
        two more, and `params` on `Scheme` is all the machinery they need.
        """
        match t:
            case Prim(name, inv):
                if name not in self.prims:
                    raise Rel42Error(f"unknown primitive: {name}")
                s = self.prims[name]
                return self.instantiate(s.swap() if inv else s)

            case Ref(name, inv) | Var(name, inv):
                if name not in env:
                    raise Rel42Error(f"undefined: {name}")
                s = env[name]
                return self.instantiate(s.swap() if inv else s)

            case Fun(param, body):
                # The parameter denotes a relation of unknown shape.  It is a
                # *monomorphic* assumption: a combinator uses its argument at one
                # type, which is what makes this decidable.
                a, b = self.fresh(), self.fresh()
                inner = self.infer(body, {**env, param: Scheme(a, b, mono=True)})
                return Scheme(
                    inner.dom, inner.cod, params=((a, b),) + inner.params
                )

            case App(f, arg):
                fs = self.infer(f, env)
                if not fs.params:
                    raise IllTyped(
                        "this is applied to an argument but takes no parameters"
                    )
                (pa, pb), rest = fs.params[0], fs.params[1:]
                got = self.infer(arg, env)
                if got.params:
                    raise IllTyped(
                        "a combinator cannot be passed as an argument: 42 is "
                        "second-order, so a parameter must denote a relation"
                    )
                self.unify(got.dom, pa, "in an application (the argument's domain)")
                self.unify(got.cod, pb, "in an application (the argument's codomain)")
                return Scheme(fs.dom, fs.cod, params=rest)

            case Seq(s, u):
                a, b = self.relation(s, env, "the left of a composition `;`")
                c, d = self.relation(u, env, "the right of a composition `;`")
                self.unify(b, c, "in a composition `;`")
                return Scheme(a, d)

            case Union(s, u):
                a, b = self.relation(s, env, "the left of a choice `|`")
                c, d = self.relation(u, env, "the right of a choice `|`")
                # Both branches are alternatives for the *same* relation, so
                # both ends must agree.
                self.unify(a, c, "in a choice `|` (the two domains differ)")
                self.unify(b, d, "in a choice `|` (the two codomains differ)")
                return Scheme(a, b)

            case Sum(s, u):
                a, b = self.relation(s, env, "the left of `+`")
                c, d = self.relation(u, env, "the right of `+`")
                return Scheme(TSum(a, c), TSum(b, d))

            case Prod(s, u):
                a, b = self.relation(s, env, "the left of `*`")
                c, d = self.relation(u, env, "the right of `*`")
                return Scheme(TProd(a, c), TProd(b, d))

            case Star(s):
                a, b = self.relation(s, env, "the body of a closure `^`")
                # A closure iterates, so it must be composable with itself.
                # This is where `pred^` acquires  nat = mu X. 1 + X.
                self.unify(a, b, "in a closure `^` (it must map a type to itself)")
                return Scheme(a, a)

        raise Rel42Error(f"not a term: {t!r}")


